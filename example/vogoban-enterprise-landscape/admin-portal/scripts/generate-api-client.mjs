#!/usr/bin/env node
/**
 * Generates src/app/api/gateway-api.paths.ts from the OpenAPI document published
 * by the platform-gateway repository.
 *
 * The portal never spells a gateway route as a string literal, so a route the
 * gateway stops publishing fails this portal's build instead of failing a page at
 * runtime. Dependency-free on purpose: node:fs and import.meta.dirname only.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const repositoryRoot = `${import.meta.dirname}/..`;
const outputPath = `${repositoryRoot}/src/app/api/gateway-api.paths.ts`;
const environmentPath = `${repositoryRoot}/src/environments/environment.ts`;

/**
 * The contract document to generate from is portal configuration rather than a
 * hardcoded path: `environment.gatewayOpenApi` names the sibling platform-gateway
 * repository's document, and this script is its consumer. The configured value is
 * relative to this repository's root.
 */
function readContractDocumentPath() {
  const environment = readFileSync(environmentPath, 'utf8');
  const match = /gatewayOpenApi:\s*'([^']+)'/.exec(environment);

  if (!match) {
    throw new Error(`environment.gatewayOpenApi is not set in ${environmentPath}.`);
  }

  return `${repositoryRoot}/${match[1]}`;
}

const documentPath = readContractDocumentPath();

/** The gateway surface is a dozen operations; anything less means the document moved or was truncated. */
const minimumOperationCount = 8;

const httpMethods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace']);

/**
 * Reads every operation from the top-level `paths` mapping. The document is
 * written with two-space indentation, so a path key sits at two spaces and the
 * method it serves at four.
 */
function readOperations(yaml) {
  const operations = [];
  let insidePaths = false;
  let current = null;

  for (const line of yaml.split(/\r?\n/)) {
    if (/^paths:\s*$/.test(line)) {
      insidePaths = true;
      continue;
    }

    if (!insidePaths) {
      continue;
    }

    if (/^\S/.test(line)) {
      break;
    }

    const methodKey = /^ {4}([a-z]+):\s*$/.exec(line);

    if (
      current !== null &&
      current.method === null &&
      methodKey !== null &&
      httpMethods.has(methodKey[1])
    ) {
      current.method = methodKey[1];

      continue;
    }

    const pathKey = /^ {2}(\S+):\s*$/.exec(line);

    if (pathKey !== null) {
      const path = pathKey[1].replace(/^["']|["']$/g, '');

      current = path.startsWith('/') ? { path, method: null } : null;

      if (current !== null) {
        operations.push(current);
      }
    }
  }

  return operations;
}

/** `Customers/{id}` becomes `CustomersById`, so `/api/Customers/{id}/orders` reads `getCustomersByIdOrders`. */
function toResourceName(path) {
  const segments = path
    .replace(/^\/api\//, '')
    .split('/')
    .filter((segment) => segment.length > 0);

  return segments
    .map((segment, index) => {
      const parameter = /^\{(.+)\}$/.exec(segment);
      const name = parameter === null ? segment : `By-${parameter[1]}`;

      const pascal = name
        .split(/[^A-Za-z0-9]+/)
        .filter((part) => part.length > 0)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');

      return index === 0 ? pascal.charAt(0).toLowerCase() + pascal.slice(1) : pascal;
    })
    .join('');
}

/** A key names one gateway operation, which is both unique and stable as the document grows. */
function toKey(operation) {
  return `${operation.method}${toResourceName(operation.path).replace(/^./, (character) => character.toUpperCase())}`;
}

function renderConstants(operations) {
  const entries = operations.map((operation) => ({ key: toKey(operation), path: operation.path }));
  const seen = new Map();

  for (const entry of entries) {
    if (seen.has(entry.key)) {
      console.error(
        `Two gateway operations share the key '${entry.key}': ${seen.get(entry.key)} and ${entry.path}.`,
      );
      process.exit(1);
    }

    seen.set(entry.key, entry.path);
  }

  return entries.map((entry) => `  ${entry.key}: '${entry.path}',`).join('\n');
}

function renderFile(operations) {
  return `/**
 * Gateway API paths, generated by scripts/generate-api-client.mjs from
 * ../platform-gateway/openapi/platform-gateway.openapi.yaml.
 *
 * Do not edit by hand. Run \`npm run generate:api\`, or \`npm run build\`, which
 * regenerates this file first.
 */

/** Every operation the platform gateway publishes, keyed by method and resource. */
export const GATEWAY_PATHS = {
${renderConstants(operations)}
} as const;

export type GatewayPathName = keyof typeof GATEWAY_PATHS;

export type GatewayPath = (typeof GATEWAY_PATHS)[GatewayPathName];

/** Substitutes the \`{name}\` placeholders of a gateway path template. */
export function buildPath(
  template: GatewayPath,
  parameters: Readonly<Record<string, string | number>> = {},
): string {
  return template.replace(/\\{([^{}]+)\\}/g, (placeholder: string, name: string) => {
    const value = parameters[name];

    if (value === undefined) {
      throw new Error(\`No value was supplied for \${placeholder} in the gateway path \${template}.\`);
    }

    return encodeURIComponent(String(value));
  });
}
`;
}

function main() {
  const yaml = readFileSync(documentPath, 'utf8');
  const operations = readOperations(yaml).filter((operation) => operation.method !== null);

  console.log(`platform-gateway <${documentPath}>`);
  console.log(`  ${operations.length} operation(s) published:`);

  for (const operation of operations) {
    console.log(`  ${operation.method.toUpperCase().padEnd(4)} ${operation.path}`);
  }

  if (operations.length < minimumOperationCount) {
    console.error(
      `The gateway document publishes ${operations.length} operation(s); at least ${minimumOperationCount} were expected.`,
    );
    process.exit(1);
  }

  const contents = renderFile(operations);

  mkdirSync(`${repositoryRoot}/src/app/api`, { recursive: true });
  writeFileSync(outputPath, contents);

  console.log(`  wrote ${operations.length} path constant(s) to ${outputPath}`);
}

main();
